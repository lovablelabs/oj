"""Copies the tsrs crates oj's type checker needs into crates/typecheck.

Usage: tools/vendor-tsrs.py <tsrs checkout>

The checkout is a clone of https://github.com/oxc-project/tsrs at the
release tag to vendor. Every crate `tsrs_api` depends on, transitively, is
copied to `crates/typecheck/oj_<name>` without its tests, benches and
examples. The package is renamed `oj_<name>`; the dependency keys stay
`tsrs_*` (each points at its renamed package), so the sources are copied
unchanged. Each manifest is made self-contained: the tsrs workspace's
dependency entries are written out inline, and the crates join oj's
workspace (version, repository) and its release profile.

Patches applied while copying:
- `unicode-id-start = "=1.1.2"` becomes `"1.1.2"`: deno's swc_ecma_ast needs
  `^1.2`, and Cargo cannot hold two 1.x versions of one crate.
- tsrs_execute's build.rs reads the tsrs workspace manifest for the
  TypeScript version; the copy embeds the values instead.
"""

import pathlib
import re
import shutil
import subprocess
import sys
import tomllib

OJ = pathlib.Path(__file__).resolve().parent.parent
DEST = OJ / "crates" / "typecheck"
ROOT_CRATE = "tsrs_api"
SKIPPED_DIRS = {"tests", "benches", "examples", "testdata", "target"}
PATCHED_VERSIONS = {"unicode-id-start": "1.1.2"}
LOCAL_CLIPPY = {"multiple_crate_versions": "allow", "cargo_common_metadata": "allow"}
BEGIN, END = "# tsrs:begin (tools/vendor-tsrs.py)", "# tsrs:end"


def main(tsrs: pathlib.Path) -> None:
    workspace = tomllib.loads((tsrs / "Cargo.toml").read_text())
    shared = workspace["workspace"]["dependencies"]
    package = workspace["workspace"]["package"]
    typescript = workspace["workspace"]["metadata"]["typescript"]
    lints = workspace["workspace"].get("lints", {})
    commit = subprocess.run(
        ["git", "-C", str(tsrs), "rev-parse", "HEAD"], capture_output=True, text=True, check=True
    ).stdout.strip()

    crates = closure(tsrs, ROOT_CRATE)
    for old in DEST.glob("oj_tsrs_*"):
        shutil.rmtree(old)
    for name in crates:
        copy_crate(tsrs, name, shared, package, typescript, lints)
    oj_version = tomllib.loads((OJ / "Cargo.toml").read_text())["workspace"]["package"]["version"]
    update_root_manifest(crates, oj_version)
    (DEST / "README.md").write_text(readme(package["version"], commit, typescript, crates))
    print(f"vendored {len(crates)} tsrs crates at {package['version']} ({commit[:12]})")


def closure(tsrs: pathlib.Path, root: str) -> list[str]:
    seen, stack = set(), [root]
    while stack:
        name = stack.pop()
        if name in seen:
            continue
        seen.add(name)
        manifest = tomllib.loads((tsrs / "crates" / name / "Cargo.toml").read_text())
        for table in dependency_tables(manifest, build=True):
            stack.extend(dep for dep in table if dep.startswith("tsrs_"))
    return sorted(seen)


def dependency_tables(manifest: dict, build: bool) -> list[dict]:
    tables = [manifest.get("dependencies", {})]
    if build:
        tables.append(manifest.get("build-dependencies", {}))
    for target in manifest.get("target", {}).values():
        tables.append(target.get("dependencies", {}))
        if build:
            tables.append(target.get("build-dependencies", {}))
    return tables


def copy_crate(tsrs: pathlib.Path, name: str, shared: dict, package: dict, typescript: dict, lints: dict) -> None:
    source = tsrs / "crates" / name
    target = DEST / f"oj_{name}"
    target.mkdir(parents=True)
    for entry in source.iterdir():
        if entry.name == "Cargo.toml" or entry.name in SKIPPED_DIRS:
            continue
        if entry.is_dir():
            shutil.copytree(entry, target / entry.name)
        else:
            shutil.copy2(entry, target / entry.name)
    for legal in ("LICENSE", "NOTICE"):
        shutil.copy2(tsrs / legal, target / legal)
    rustfmt = next(p for p in (tsrs / ".rustfmt.toml", tsrs / "rustfmt.toml") if p.is_file())
    shutil.copy2(rustfmt, target / "rustfmt.toml")
    # Its paths name the crates; inside each crate the name is now `oj_tsrs_*`.
    clippy = (tsrs / "clippy.toml").read_text().replace('"tsrs_', '"oj_tsrs_')
    (target / "clippy.toml").write_text(clippy)
    manifest = tomllib.loads((source / "Cargo.toml").read_text())
    (target / "Cargo.toml").write_text(rewrite_manifest(name, manifest, shared, package, lints))
    if name == "tsrs_execute":
        (target / "build.rs").write_text(execute_build_rs(package["version"], typescript))


def rewrite_manifest(name: str, manifest: dict, shared: dict, package: dict, lints: dict) -> str:
    out = [
        "# Generated by tools/vendor-tsrs.py from tsrs's crates/" + name + "; do not edit by hand.",
        "[package]",
        f'name = "oj_{name}"',
        "version.workspace = true",
        f'edition = "{package["edition"]}"',
        f'rust-version = "{package["rust-version"]}"',
        f'license = "{package["license"]}"',
        f'description = "tsrs\'s {name}, vendored for oj\'s type checker"',
        "repository.workspace = true",
    ]
    for key, value in manifest["package"].items():
        if key in {"name", "version", "edition", "rust-version", "license", "publish", "description", "repository"}:
            continue
        out.append(f"{key} = {toml_value(value)}")
    if "lib" in manifest:
        out += ["", "[lib]"] + [f"{k} = {toml_value(v)}" for k, v in manifest["lib"].items()]
    if "features" in manifest:
        out += ["", "[features]"] + [f"{toml_key(k)} = {toml_value(v)}" for k, v in manifest["features"].items()]
    if manifest.get("lints", {}).get("workspace"):
        # tsrs's own lint policy (its code is clean under it, and its
        # `#[expect]`s need it); the cargo group's checks are for tsrs's
        # workspace and lockfile, not oj's.
        for tool, table in lints.items():
            table = dict(table)
            if tool == "clippy":
                table.update(LOCAL_CLIPPY)
            out += ["", f"[lints.{tool}]"] + [f"{toml_key(k)} = {toml_value(v)}" for k, v in table.items()]
    for header, table in sections(manifest):
        out += ["", header] + [f"{toml_key(dep)} = {toml_value(dependency(dep, spec, shared))}" for dep, spec in table.items()]
    return "\n".join(out) + "\n"


def sections(manifest: dict):
    for kind in ("dependencies", "build-dependencies"):
        if manifest.get(kind):
            yield f"[{kind}]", manifest[kind]
    for cfg, target in manifest.get("target", {}).items():
        for kind in ("dependencies", "build-dependencies"):
            if target.get(kind):
                yield f"[target.{toml_key(cfg)}.{kind}]", target[kind]


def dependency(dep: str, spec, shared: dict) -> dict:
    spec = {"version": spec} if isinstance(spec, str) else dict(spec)
    if dep.startswith("tsrs_"):
        spec.pop("path", None)
        spec["workspace"] = True
        return spec
    if spec.pop("workspace", False):
        base = shared[dep]
        base = {"version": base} if isinstance(base, str) else dict(base)
        features = base.get("features", []) + [f for f in spec.pop("features", []) if f not in base.get("features", [])]
        base.update(spec)
        if features:
            base["features"] = features
        spec = base
    if dep in PATCHED_VERSIONS:
        spec["version"] = PATCHED_VERSIONS[dep]
    return spec


def toml_key(key: str) -> str:
    return key if re.fullmatch(r"[A-Za-z0-9_-]+", key) else '"' + key.replace('"', '\\"') + '"'


def toml_value(value) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, str):
        return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'
    if isinstance(value, list):
        return "[" + ", ".join(toml_value(v) for v in value) + "]"
    if isinstance(value, dict):
        return "{ " + ", ".join(f"{toml_key(k)} = {toml_value(v)}" for k, v in value.items()) + " }"
    raise TypeError(f"no TOML form for {value!r}")


def execute_build_rs(version: str, typescript: dict) -> str:
    return f"""// Generated by tools/vendor-tsrs.py: tsrs's build.rs reads these from its
// workspace manifest, which oj does not vendor.

fn main() {{
    println!("cargo:rustc-env=TSRS_RELEASE_VERSION={version}-ts{typescript['version']}");
    println!("cargo:rustc-env=TSRS_TYPESCRIPT_COMMIT={typescript['commit'][:12]}");
}}
"""


def update_root_manifest(crates: list[str], oj_version: str) -> None:
    path = OJ / "Cargo.toml"
    text = path.read_text()
    deps = "\n".join(
        f'{name} = {{ package = "oj_{name}", version = "{oj_version}", path = "crates/typecheck/oj_{name}" }}'
        for name in crates
    )
    # The checker is hot: oj's release profile optimizes for size by default.
    profile = "\n".join(f"oj_{name} = {{ opt-level = 3 }}" for name in crates)
    text = replace_block(text, "deps", deps)
    text = replace_block(text, "profile", profile)
    path.write_text(text)


def replace_block(text: str, label: str, body: str) -> str:
    begin, end = f"{BEGIN} {label}", f"{END} {label}"
    pattern = re.compile(re.escape(begin) + r"\n.*?" + re.escape(end), re.S)
    if not pattern.search(text):
        sys.exit(f"Cargo.toml has no `{begin}` ... `{end}` block")
    return pattern.sub(lambda _: f"{begin}\n{body}\n{end}", text)


def readme(version: str, commit: str, typescript: dict, crates: list[str]) -> str:
    listing = "\n".join(f"- `oj_{c}`" for c in crates)
    return f"""# Type checker crates

`oj_typecheck` is oj's TypeScript type checker (`oj typecheck`, and
`/@oj/typecheck` under `OJ_TYPECHECK=1`). It runs on
[tsrs](https://github.com/oxc-project/tsrs), the Rust port of the
TypeScript 7 compiler, whose crates are vendored here as `oj_tsrs_*`.

Vendored: tsrs {version} (`{commit}`), TypeScript {typescript['version']}.
Licensed Apache-2.0; each crate carries tsrs's `LICENSE` and `NOTICE`.

Do not edit the `oj_tsrs_*` crates by hand. To move to another tsrs
release, check it out and rerun the script, which also rewrites the
`tsrs:` blocks of the root `Cargo.toml`:

```sh
git clone --depth 1 --branch v<version> https://github.com/oxc-project/tsrs /tmp/tsrs
tools/vendor-tsrs.py /tmp/tsrs
```

The script's docstring lists the patches it applies.

{listing}
"""


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(pathlib.Path(sys.argv[1]).resolve())
