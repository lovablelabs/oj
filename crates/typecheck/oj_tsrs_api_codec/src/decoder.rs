/// Go `childIterator`.
pub(crate) struct ChildIter<'a> {
    indices: &'a [usize],
    pos: usize,
}

impl<'a> ChildIter<'a> {
    pub(crate) fn new(indices: &'a [usize]) -> ChildIter<'a> {
        ChildIter { indices, pos: 0 }
    }

    pub(crate) fn next_if(&mut self, mask: u8, bit: u8) -> usize {
        if mask & (1 << bit) == 0 {
            return 0;
        }
        let Some(&ci) = self.indices.get(self.pos) else {
            return 0;
        };
        self.pos += 1;
        ci
    }
}

/// Converts a decoded child into a factory parameter: required children must be present (Go would store nil).
pub(crate) trait FromChild<T>: Sized {
    fn from_child(v: Option<T>) -> Result<Self, DecodeError>;
}
impl<T> FromChild<T> for Option<T> {
    fn from_child(v: Option<T>) -> Result<Self, DecodeError> {
        Ok(v)
    }
}
impl FromChild<P<Node>> for P<Node> {
    fn from_child(v: Option<P<Node>>) -> Result<Self, DecodeError> {
        v.ok_or(DecodeError::MissingChild)
    }
}
impl FromChild<P<NodeList>> for P<NodeList> {
    fn from_child(v: Option<P<NodeList>>) -> Result<Self, DecodeError> {
        v.ok_or(DecodeError::MissingChild)
    }
}
pub(crate) fn from_node<R: FromChild<P<Node>>>(v: Option<P<Node>>) -> Result<R, DecodeError> {
    R::from_child(v)
}
pub(crate) fn from_list<R: FromChild<P<NodeList>>>(
    v: Option<P<NodeList>>,
) -> Result<R, DecodeError> {
    R::from_child(v)
}

/// The Go zero value of a factory parameter the binary format does not carry (`goDefaultValue`); a required
/// child has none, so it is a decode error.
pub(crate) trait Absent: Sized {
    fn absent() -> Result<Self, DecodeError>;
}
macro_rules! absent_default {
    ($($t:ty),*) => {$(impl Absent for $t { fn absent() -> Result<Self, DecodeError> { Ok(<$t>::default()) } })*};
}
absent_default!(bool, Kind, TokenFlags, NodeFlags, &'static str);
impl<T> Absent for Option<T> {
    fn absent() -> Result<Self, DecodeError> {
        Ok(None)
    }
}
impl<T> Absent for &'static [T] {
    fn absent() -> Result<Self, DecodeError> {
        Ok(&[])
    }
}
impl Absent for P<Node> {
    fn absent() -> Result<Self, DecodeError> {
        Err(DecodeError::MissingChild)
    }
}
impl Absent for P<NodeList> {
    fn absent() -> Result<Self, DecodeError> {
        Err(DecodeError::MissingChild)
    }
}
pub(crate) fn absent<T: Absent>() -> Result<T, DecodeError> {
    T::absent()
}

/// Go `decodeNodeCommonData_SyntheticExpression` panics: the node is checker-internal and never decoded.
pub(crate) fn decode_node_common_data_synthetic_expression(
    _: u32,
) -> Result<(&'static dyn std::any::Any, bool), DecodeError> {
    Err(DecodeError::Unsupported(Kind::SyntheticExpression))
}
