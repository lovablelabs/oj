//! `GET /@oj/tanstack/routes.json` on a real `oj dev` of a TanStack Start
//! app: the routes of the generated route tree, for a host UI's route
//! picker. A file-routed app lists its routes, a route file added while the
//! server runs appears once the generator has rewritten the tree, the
//! answer is oj's own (not the app's 404) behind the dev server's host
//! check, and documents are served as before. An app whose routes are
//! code-based (the fixture as it is) has a generated tree with the root
//! alone, so it lists none; under a `base` the URL answers with and without
//! the prefix, as oj's other URLs do.

#[allow(dead_code)]
mod start_app;

use std::time::{Duration, Instant};

use start_app::{app, Server};

const URL: &str = "/@oj/tanstack/routes.json";

const ROOT: &str = r#"import { createRootRoute, HeadContent, Outlet, Scripts } from "@tanstack/react-router";

export const Route = createRootRoute({
  head: () => ({ meta: [{ title: "routes json" }] }),
  component: () => (
    <html lang="en">
      <head>
        <HeadContent />
      </head>
      <body>
        <Outlet />
        <Scripts />
      </body>
    </html>
  ),
});
"#;

const ROUTER: &str = r#"import { createRouter } from "@tanstack/react-router";
import { routeTree } from "./routeTree.gen";

export function getRouter() {
  return createRouter({ routeTree });
}
"#;

/// A route file for `path` rendering `marker`.
fn route(path: &str, marker: &str) -> String {
    format!(
        r#"import {{ createFileRoute }} from "@tanstack/react-router";

export const Route = createFileRoute("{path}")({{
  component: () => <p>{marker}</p>,
}});
"#
    )
}

fn routes(dev: &Server) -> serde_json::Value {
    let (status, body) = dev.request("GET", URL, &[]);
    assert_eq!(status, 200, "GET {URL}\n{body}\n{}", dev.output());
    serde_json::from_str(&body).unwrap_or_else(|e| panic!("{URL} is not JSON ({e}): {body}"))
}

#[test]
fn the_route_list_follows_the_generated_tree() {
    let Some(app) = app("routes-json") else {
        return;
    };
    let root = &app.0;
    let dir = root.join("src/routes");
    std::fs::remove_dir_all(&dir).unwrap();
    std::fs::create_dir_all(dir.join("_shell")).unwrap();
    for (file, code) in [
        ("__root.tsx", ROOT.to_string()),
        ("index.tsx", route("/", "home page")),
        ("posts.$postId.tsx", route("/posts/$postId", "a post")),
        ("files.$.tsx", route("/files/$", "a file")),
        ("_shell.tsx", route("/_shell", "shell")),
        ("_shell/dash.tsx", route("/_shell/dash", "dash")),
    ] {
        std::fs::write(dir.join(file), code).unwrap();
    }
    std::fs::write(root.join("src/routeTree.ts"), "export {};\n").unwrap();
    std::fs::write(root.join("src/router.tsx"), ROUTER).unwrap();
    // The fixture's own tree is for its code-based routes; the generator
    // writes this app's at boot.
    let _ = std::fs::remove_file(root.join("src/routeTree.gen.ts"));
    let dev = Server::oj_dev(root);

    // A document is served as before (and the tree is generated by now).
    let (status, home) = dev.request("GET", "/", &[]);
    assert!(
        status == 200 && home.contains("home page"),
        "GET /: {status}\n{home}\n{}",
        dev.output()
    );

    let (status, headers, body) = dev.fetch("GET", URL, &[]);
    let header = |name: &str| {
        headers
            .iter()
            .find(|(n, _)| n == name)
            .map(|(_, v)| v.as_str())
    };
    assert_eq!(status, 200, "{}", dev.output());
    assert_eq!(header("content-type"), Some("application/json"));
    assert_eq!(header("cache-control"), Some("no-store"));
    let listed: serde_json::Value = serde_json::from_slice(&body).unwrap();
    assert_eq!(
        listed,
        serde_json::json!({
            "routes": [
                { "path": "/", "id": "/", "file": "src/routes/index.tsx" },
                { "path": "/dash", "id": "/_shell/dash", "file": "src/routes/_shell/dash.tsx" },
                {
                    "path": "/files/$",
                    "id": "/files/$",
                    "file": "src/routes/files.$.tsx",
                    "params": ["_splat"],
                },
                {
                    "path": "/posts/$postId",
                    "id": "/posts/$postId",
                    "file": "src/routes/posts.$postId.tsx",
                    "params": ["postId"],
                },
            ]
        }),
        "{}",
        dev.output()
    );

    // A query is no other URL; HEAD answers; anything else is refused by oj,
    // not handed to the app.
    assert_eq!(dev.request("GET", &format!("{URL}?t=1"), &[]).0, 200);
    assert_eq!(dev.request("HEAD", URL, &[]).0, 200);
    for method in ["POST", "PUT", "DELETE"] {
        let (status, headers, _) = dev.fetch(method, URL, &[]);
        assert_eq!(status, 405, "{method} {URL}");
        assert!(
            headers
                .iter()
                .any(|(n, v)| n == "allow" && v == "GET, HEAD"),
            "{method} {URL}: {headers:?}"
        );
    }
    // Behind the dev server's host check, like the page itself.
    let (status, body) = dev.request("GET", URL, &[("Host", "evil.example".to_string())]);
    assert!(
        status == 403 && !body.contains("routes"),
        "a host that is not allowed got {status}\n{body}"
    );

    // A route file added while the server runs is listed once the generator
    // has rewritten the tree.
    std::fs::write(dir.join("about.tsx"), route("/about", "about page")).unwrap();
    let deadline = Instant::now() + start_app::WAIT;
    let about =
        serde_json::json!({ "path": "/about", "id": "/about", "file": "src/routes/about.tsx" });
    loop {
        let listed = routes(&dev);
        let all = listed["routes"].as_array().unwrap();
        if all.contains(&about) {
            assert_eq!(all.len(), 5, "{listed}");
            break;
        }
        assert!(
            Instant::now() < deadline,
            "/about never listed: {listed}\n{}",
            dev.output()
        );
        std::thread::sleep(Duration::from_millis(100));
    }
    // The tree is written before the server has rebuilt on it, so the list
    // can name the route a moment before its document renders.
    loop {
        let (status, html) = dev.request("GET", "/about", &[]);
        if status == 200 && html.contains("about page") {
            break;
        }
        assert!(
            Instant::now() < deadline,
            "GET /about: {status}\n{html}\n{}",
            dev.output()
        );
        std::thread::sleep(Duration::from_millis(100));
    }
}

#[test]
fn code_based_routes_list_none_and_a_base_answers_with_and_without_its_prefix() {
    let Some(app) = app("routes-json-base") else {
        return;
    };
    let config = app.0.join("vite.config.ts");
    let text = std::fs::read_to_string(&config).unwrap();
    let with_base = text.replacen(
        "export default defineConfig({",
        "export default defineConfig({\n  base: \"/app/\",",
        1,
    );
    assert_ne!(text, with_base, "the fixture's config changed shape");
    std::fs::write(&config, with_base).unwrap();
    let dev = Server::oj_dev(&app.0);
    for url in [format!("/app{URL}"), URL.to_string()] {
        let (status, body) = dev.request("GET", &url, &[]);
        assert_eq!(
            (status, body.as_str()),
            (200, r#"{"routes":[]}"#),
            "GET {url}\n{}",
            dev.output()
        );
    }
}
